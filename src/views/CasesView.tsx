import React, { useMemo, useState } from 'react';
import { useNexus } from '../store/useNexusStore';
import { StatusBadge } from '../components/common/StatusBadge';
import { FolderKanban, Search, ArrowUpDown, ArrowRight } from 'lucide-react';

type Partition = 'ACTIVE' | 'RESOLVED' | 'ALL';

export const CasesView: React.FC = () => {
  const { cases, openCase } = useNexus();
  const [search, setSearch] = useState('');
  const [partition, setPartition] = useState<Partition>('ACTIVE');
  const [sortBy, setSortBy] = useState<'priority' | 'risk' | 'exposure' | 'evidence'>('priority');

  const resolvedStatuses = new Set(['RESOLVED_FWA', 'CLOSED_NOT_FWA', 'FALSE_POSITIVE']);

  const filtered = useMemo(() => {
    return cases
      .filter((c) => {
        if (partition === 'ACTIVE' && resolvedStatuses.has(c.status)) return false;
        if (partition === 'RESOLVED' && !resolvedStatuses.has(c.status)) return false;
        const q = search.toLowerCase();
        return (
          q === '' ||
          c.id.toLowerCase().includes(q) ||
          c.targetName.toLowerCase().includes(q) ||
          c.targetId.toLowerCase().includes(q)
        );
      })
      .sort((a, b) => {
        if (sortBy === 'risk') return b.riskScore - a.riskScore;
        if (sortBy === 'exposure') return b.estimatedExposure - a.estimatedExposure;
        if (sortBy === 'evidence') return b.evidenceStrength - a.evidenceStrength;
        return b.priorityScore - a.priorityScore;
      });
  }, [cases, partition, search, sortBy]);

  return (
    <div className="p-8 max-w-7xl mx-auto space-y-6 animate-in fade-in duration-150">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-slate-200">
        <div>
          <div className="flex items-center gap-2">
            <FolderKanban className="w-5 h-5 text-blue-600" />
            <h1 className="text-xl font-bold tracking-tight text-slate-900">Cases</h1>
          </div>
          <p className="text-xs text-slate-500 mt-1">
            Every SIU case generated by the analytical pipeline. Open a case to enter the investigation workbench.
          </p>
        </div>
        <div className="flex items-center p-1 rounded-xl bg-slate-100 border border-slate-200 text-xs">
          {(['ACTIVE', 'RESOLVED', 'ALL'] as Partition[]).map((p) => (
            <button
              key={p}
              onClick={() => setPartition(p)}
              className={`px-3.5 py-1.5 rounded-lg font-medium transition-all ${
                partition === p ? 'bg-white text-slate-900 font-semibold shadow-xs' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              {p.charAt(0) + p.slice(1).toLowerCase()}
            </button>
          ))}
        </div>
      </div>

      <div className="flex flex-wrap items-center justify-between gap-3 p-3 bg-white border border-slate-200 rounded-xl text-xs">
        <div className="flex items-center gap-2 flex-1 min-w-[240px] max-w-md bg-slate-50 border border-slate-200 rounded-lg px-2.5 py-1.5">
          <Search className="w-3.5 h-3.5 text-slate-400 shrink-0" />
          <input
            type="text"
            placeholder="Search case, provider name or ID..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            className="w-full bg-transparent text-slate-800 placeholder-slate-400 focus:outline-none"
          />
        </div>
        <div className="flex items-center gap-2">
          <ArrowUpDown className="w-3.5 h-3.5 text-slate-400" />
          <span className="text-slate-500">Sort by:</span>
          <select
            value={sortBy}
            onChange={(e) => setSortBy(e.target.value as typeof sortBy)}
            className="bg-slate-50 border border-slate-200 rounded-lg px-2.5 py-1 text-slate-700 font-medium focus:outline-none"
          >
            <option value="priority">Priority</option>
            <option value="risk">Risk Score</option>
            <option value="exposure">Exposure</option>
            <option value="evidence">Evidence Strength</option>
          </select>
        </div>
      </div>

      <div className="bg-white rounded-xl border border-slate-200 overflow-hidden">
        <div className="px-5 py-3 border-b border-slate-100 text-xs text-slate-500">
          Showing <strong>{filtered.length}</strong> cases
        </div>
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead className="bg-slate-50 border-b border-slate-200 text-slate-500 uppercase text-[10px] font-semibold">
              <tr>
                <th className="py-3 px-4">Case</th>
                <th className="py-3 px-4">Target Entity</th>
                <th className="py-3 px-4 text-center">Risk</th>
                <th className="py-3 px-4 text-center">Evidence</th>
                <th className="py-3 px-4 text-right">Exposure</th>
                <th className="py-3 px-4">Member Impact</th>
                <th className="py-3 px-4">Network</th>
                <th className="py-3 px-4">Status</th>
                <th className="py-3 px-4 text-right">Action</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {filtered.map((c) => (
                <tr key={c.id} onClick={() => openCase(c.id)} className="hover:bg-slate-50/80 cursor-pointer transition-colors group">
                  <td className="py-3 px-4 font-mono font-semibold text-slate-900">
                    <span className="group-hover:text-blue-600 transition-colors">{c.id}</span>
                    <span className="text-[10px] text-slate-400 block font-sans">Priority {c.priorityScore}</span>
                  </td>
                  <td className="py-3 px-4">
                    <div className="font-semibold text-slate-800">{c.targetName}</div>
                    <div className="text-[11px] text-slate-500 font-mono">{c.targetId} · {c.specialty || 'Provider'}</div>
                  </td>
                  <td className="py-3 px-4 text-center">
                    <span className={`inline-block px-2 py-0.5 rounded text-xs font-bold font-mono ${
                      c.riskScore >= 85 ? 'bg-rose-50 text-rose-700 border border-rose-200'
                      : c.riskScore >= 70 ? 'bg-amber-50 text-amber-800 border border-amber-200'
                      : 'bg-slate-100 text-slate-700 border border-slate-200'}`}>
                      {c.riskScore}
                    </span>
                  </td>
                  <td className="py-3 px-4 text-center font-mono">
                    <span className="font-semibold text-slate-700">{c.evidenceStrength}%</span>
                    <span className="text-[10px] text-slate-400 block font-sans">{c.evidenceBreakdown.length} signals</span>
                  </td>
                  <td className="py-3 px-4 text-right font-mono font-semibold text-slate-900">${c.estimatedExposure.toLocaleString()}</td>
                  <td className="py-3 px-4">
                    <span className="text-slate-800 font-medium">{c.affectedMembersCount} members</span>
                    <span className={`text-[10px] px-1.5 py-0.5 rounded ml-1.5 font-medium ${c.memberImpactTier === 'HIGH' ? 'bg-rose-50 text-rose-700' : 'bg-slate-100 text-slate-600'}`}>{c.memberImpactTier}</span>
                  </td>
                  <td className="py-3 px-4">
                    <span className="font-mono text-slate-700 font-medium">{c.networkId || '—'}</span>
                    {c.networkId && <span className="text-[10px] px-1.5 py-0.5 rounded ml-1.5 font-bold font-mono bg-purple-50 text-purple-700">{c.networkRiskScore}</span>}
                  </td>
                  <td className="py-3 px-4"><StatusBadge status={c.status} /></td>
                  <td className="py-3 px-4 text-right">
                    <button
                      onClick={(e) => { e.stopPropagation(); openCase(c.id); }}
                      className="px-3 py-1 rounded-lg bg-blue-600 hover:bg-blue-700 text-white font-semibold text-xs transition-colors inline-flex items-center gap-1"
                    >
                      Open Case <ArrowRight className="w-3 h-3" />
                    </button>
                  </td>
                </tr>
              ))}
              {filtered.length === 0 && (
                <tr><td colSpan={9} className="py-10 text-center text-slate-500 text-xs">No cases match the current filter.</td></tr>
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
};
